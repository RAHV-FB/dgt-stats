"""The catalogue written out: ``docs/catalogue.md`` and a ``README.md`` in each table folder.

``docs/catalogue.md`` is the map of the project: for each section, the question it answers, its
sources, its pipeline stages, its tables, documents and pages; then every source with the files it
owns and the tables that read it. Each folder ``reports/tables/<section>/`` gets a ``README.md``
listing its tables: what each holds, the sources it is computed from, the stage that writes it and
the site pages that link it for download. Both are generated from :mod:`dgt_stats.catalogue`,
:mod:`dgt_stats.pipeline` and the built pages, so they cannot drift from the code; a test compares
them with what this module would write.
"""

from __future__ import annotations

import logging
import re
from collections import defaultdict
from pathlib import Path

from dgt_stats import catalogue, pipeline
from dgt_stats.paths import DOCS_DIR, MANIFEST, PROJECT_ROOT, TABLES_DIR

log = logging.getLogger(__name__)

CATALOGUE_DOC = DOCS_DIR / "catalogue.md"
SITE_DIR = PROJECT_ROOT / "site"
SITE_URL = "https://rahv-fb.github.io/dgt-stats"
HEADER = (
    "Generated by `python scripts/run.py sources.catalogue` from `src/dgt_stats/catalogue.py`; "
    "do not edit by hand."
)
# The raw-file inventory reads every file; it is left out where a section's sources are listed.
INVENTORY_TABLE = "data_inventory"


def _page_titles() -> dict[str, str]:
    from dgt_stats.site.components import ALL_PAGES

    return dict(ALL_PAGES)


def published_on(site_dir: Path = SITE_DIR) -> dict[str, list[str]]:
    """The site pages that link each result table for download, from the built pages."""
    pages: dict[str, list[str]] = defaultdict(list)
    for page in sorted(site_dir.glob("*.html")):
        for name in sorted(
            set(re.findall(r'href="tables/([^"/]+)\.csv"', page.read_text("utf-8")))
        ):
            pages[name].append(page.stem)
    return pages


def raw_files() -> list[str]:
    """Every file listed in the manifest, relative to ``data/raw``."""
    lines = MANIFEST.read_text(encoding="utf-8").splitlines()[1:]
    return sorted(line.split(",", 1)[0] for line in lines if line)


def files_by_source() -> dict[str, list[str]]:
    owned: dict[str, list[str]] = defaultdict(list)
    for relative in raw_files():
        owned[catalogue.source_of_file(relative).key].append(relative)
    return owned


def _source_names(keys) -> str:
    if set(keys) == set(catalogue.FILE_SOURCES):
        return "every raw file"
    names = [catalogue.SOURCE_BY_KEY[key].name for key in keys]
    return ", ".join(names) if names else "definitions in the code"


def _folders(files: list[str]) -> str:
    folders = sorted({str(Path(f).parent) for f in files})
    return ", ".join(f"`{folder}/`" for folder in folders)


def _link_page(slug: str, titles: dict[str, str]) -> str:
    return f"[{titles.get(slug, slug)}]({SITE_URL}/{slug}.html)"


def section_stages(section: str) -> list[pipeline.Stage]:
    return [stage for stage in pipeline.STAGES if stage.section == section]


def document(site_dir: Path = SITE_DIR) -> str:
    titles = _page_titles()
    owned = files_by_source()
    by_section: dict[str, list[catalogue.Table]] = defaultdict(list)
    for entry in catalogue.TABLES:
        by_section[entry.section].append(entry)
    lines = [
        "# Catalogue: where every result comes from",
        "",
        HEADER,
        "",
        "The study is organised in five sections. Each has its own sources, its own stages in the "
        "pipeline (`python scripts/run.py <section>`), its own code (`src/dgt_stats/<section>/`), "
        "result tables (`reports/tables/<section>/`), documents (`docs/<section>/`) and pages on "
        "the site. No record is linked across sources; where two sources meet, it is at an "
        "aggregate both genuinely have (province and year) or as a model trained on one and "
        "tested on the other's records.",
        "",
        "| Section | What it answers | Sources | Result tables | Pages |",
        "|---|---|---|---|---|",
    ]
    for section in catalogue.SECTIONS:
        tables = by_section[section.key]
        sources = catalogue.sources_of(
            entry.name for entry in tables if entry.name != INVENTORY_TABLE
        )
        source_text = ", ".join(source.name for source in sources) or "every raw file"
        pages = ", ".join(_link_page(slug, titles) for slug in section.pages)
        lines.append(
            f"| [{section.title}](#{section.key}) | {section.question} | {source_text} | "
            f"[{len(tables)} tables](../reports/tables/{section.key}/) | {pages} |"
        )
    for section in catalogue.SECTIONS:
        lines += _section_block(section, by_section[section.key], titles)
    lines += _sources_block(owned)
    return "\n".join(lines) + "\n"


def _section_block(
    section: catalogue.Section, tables: list[catalogue.Table], titles: dict[str, str]
) -> list[str]:
    docs = sorted((DOCS_DIR / section.key).rglob("*.md"))
    lines = [
        "",
        f'<a id="{section.key}"></a>',
        "",
        f"## {section.title}",
        "",
        section.question,
        "",
        f"- **Code:** `src/dgt_stats/{section.key}/`",
        f"- **Run:** `python scripts/run.py {section.key}`",
        f"- **Result tables:** [`reports/tables/{section.key}/`](../reports/tables/{section.key}/)",
        "- **Documents:** "
        + (
            ", ".join(f"[`{p.relative_to(DOCS_DIR)}`]({p.relative_to(DOCS_DIR)})" for p in docs)
            or "none"
        ),
        "- **Pages:** " + ", ".join(_link_page(slug, titles) for slug in section.pages),
        "",
        "| Stage | What it does | Sources | Writes |",
        "|---|---|---|---|",
    ]
    for stage in section_stages(section.key):
        written = [entry for entry in tables if entry.stage == stage.key]
        if written:
            keys = {key for entry in written for key in entry.sources}
            sources = _source_names([s.key for s in catalogue.SOURCES if s.key in keys])
        else:
            sources = "—"
        note = "" if stage.in_all else " (run by name only)"
        count = f" ({len(written)} tables)" if written else ""
        lines.append(f"| `{stage.key}`{note} | {stage.does} | {sources} | {stage.writes}{count} |")
    return lines


def _sources_block(owned: dict[str, list[str]]) -> list[str]:
    lines = [
        "",
        '<a id="sources-list"></a>',
        "",
        "## Every source",
        "",
        "Each raw file under `data/raw` belongs to exactly one source; the manifest "
        "(`data/raw/manifest.csv`) records its size, checksum, URL and the date it was added, and "
        "the [raw-file inventory](sources/raw_file_inventory.md) profiles it. Two sources are "
        "figures typed from documents that are not archived, and say so. The terms on which "
        "each may be reused are in the [source register](sources/register.md).",
        "",
        "| Source | Publisher | Coverage | One record | Files | Read by |",
        "|---|---|---|---|---|---|",
    ]
    unread = []
    for source in catalogue.SOURCES:
        if not source.read:
            unread.append(source)
            continue
        files = owned.get(source.key, [])
        file_text = f"{_folders(files)} ({len(files)} files)" if files else "typed; not archived"
        lines.append(
            f"| {source.name} | {source.publisher} | {source.coverage} | {source.record}"
            + (f" ({source.note})" if source.note else "")
            + f" | {file_text} | {_readers(source.key)} |"
        )
    lines += [
        "",
        "### Kept as a record, read by no analysis",
        "",
        "| Files | What they are |",
        "|---|---|",
    ]
    for source in unread:
        files = owned.get(source.key, [])
        lines.append(f"| {_folders(files)} ({len(files)} files) | {source.name}: {source.record} |")
    return lines


def _readers(key: str) -> str:
    counts: dict[str, int] = defaultdict(int)
    for entry in catalogue.tables_reading(key):
        if entry.name != INVENTORY_TABLE:
            counts[entry.section] += 1
    return ", ".join(
        f"[{section.key}](#{section.key}) ({counts[section.key]})"
        for section in catalogue.SECTIONS
        if counts.get(section.key)
    )


def folder_readme(section: catalogue.Section, site_dir: Path = SITE_DIR) -> str:
    published = published_on(site_dir)
    titles = _page_titles()
    lines = [
        f"# {section.title}: result tables",
        "",
        HEADER,
        "",
        section.question,
        "",
        "Each table's sources are the data its values are computed from; the stage is the one "
        "`python scripts/run.py <stage>` runs to write it. Tables linked from a page are "
        "published on the site as downloads; the others stand behind a document, a figure or a "
        "check. The map of all sections is [`docs/catalogue.md`](../../../docs/catalogue.md).",
        "",
        "| Table | What it holds | Sources | Written by | On the site |",
        "|---|---|---|---|---|",
    ]
    for entry in catalogue.TABLES:
        if entry.section != section.key:
            continue
        pages = ", ".join(_link_page(slug, titles) for slug in published.get(entry.name, []))
        lines.append(
            f"| [`{entry.name}`]({entry.name}.csv) | {entry.description} | "
            f"{_source_names(entry.sources)} | `{entry.stage}` | {pages or '—'} |"
        )
    return "\n".join(lines) + "\n"


def outputs(site_dir: Path = SITE_DIR) -> dict[Path, str]:
    """Every file this module writes, with its text."""
    out = {CATALOGUE_DOC: document(site_dir)}
    for section in catalogue.SECTIONS:
        out[TABLES_DIR / section.key / "README.md"] = folder_readme(section, site_dir)
    return out


def write(site_dir: Path = SITE_DIR) -> list[Path]:
    written = []
    for path, text in outputs(site_dir).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
        log.info("wrote %s", path.relative_to(PROJECT_ROOT))
    return written
